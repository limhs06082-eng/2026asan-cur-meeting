import puppeteer from 'puppeteer-core';
const B = 'http://127.0.0.1:8080/v1/projects/demo-asan/databases/(default)/documents/workspaces/asan/members';
const H = { Authorization: 'Bearer owner', 'Content-Type': 'application/json' };
const list = await fetch(`${B}?pageSize=50`, { headers: H }).then((r) => r.json());
const t = list.documents.find((d) => d.fields.email?.stringValue === 'teacher3@school.kr');
const uid = t.name.split('/').pop();
const setActive = (v) => fetch(`${B}/${uid}?updateMask.fieldPaths=active`, { method: 'PATCH', headers: H, body: JSON.stringify({ fields: { active: { booleanValue: v } } }) });
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message.slice(0, 150)));
await page.goto('http://localhost:5174/?devLogin=teacher3@school.kr#board', { waitUntil: 'networkidle2' }).catch(() => {});
await page.waitForSelector('.chip', { timeout: 30000 });
await setActive(false);
await new Promise((r) => setTimeout(r, 4000));
const after = await page.evaluate(() => document.body.innerText.slice(0, 80));
await setActive(true);
await new Promise((r) => setTimeout(r, 4000));
const back = await page.evaluate(() => document.body.innerText.slice(0, 60));
console.log(JSON.stringify({ after, back, errs }));
await browser.close();
